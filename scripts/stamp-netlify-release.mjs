import { mkdir, readFile, rename, writeFile } from "node:fs/promises";
import { dirname } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const RELEASE_SHA_PATTERN = /^[a-f0-9]{40}$/;
const OUTPUT_URL = new URL(
  "../netlify/functions/_shared/studio-release.generated.mts",
  import.meta.url,
);

export function renderReleaseModule(releaseSha) {
  if (releaseSha !== null && !RELEASE_SHA_PATTERN.test(releaseSha)) {
    throw new Error("COMMIT_REF must be an exact lowercase 40-character Git SHA");
  }
  const value = releaseSha === null ? "null" : JSON.stringify(releaseSha);
  return [
    "// Generated by scripts/stamp-netlify-release.mjs. Do not edit.",
    `export const STUDIO_BUILD_RELEASE_SHA: string | null = ${value};`,
    "",
  ].join("\n");
}

export function releaseShaFromModule(source) {
  const match = source.match(
    /STUDIO_BUILD_RELEASE_SHA: string \| null = (null|"([a-f0-9]{40})");/,
  );
  if (!match) throw new Error("generated release module is invalid");
  return match[1] === "null" ? null : match[2];
}

async function writeReleaseModule(releaseSha) {
  const outputPath = fileURLToPath(OUTPUT_URL);
  const temporaryPath = `${outputPath}.${process.pid}.tmp`;
  await mkdir(dirname(outputPath), { recursive: true });
  await writeFile(temporaryPath, renderReleaseModule(releaseSha), "utf8");
  await rename(temporaryPath, outputPath);
}

async function main() {
  const args = process.argv.slice(2);
  if (args[0] === "--verify") {
    if (args.length !== 2 || !RELEASE_SHA_PATTERN.test(args[1])) {
      throw new Error("--verify requires one exact lowercase 40-character Git SHA");
    }
    const actual = releaseShaFromModule(await readFile(OUTPUT_URL, "utf8"));
    if (actual !== args[1]) throw new Error("generated release SHA does not match");
    return;
  }

  const allowUnstamped = args.length === 1 && args[0] === "--allow-unstamped";
  if (args.length !== 0 && !allowUnstamped) {
    throw new Error("unsupported arguments");
  }
  const rawReleaseSha = (process.env.COMMIT_REF || "").trim();
  if (!rawReleaseSha) {
    if (!allowUnstamped) {
      throw new Error("Netlify build COMMIT_REF is required");
    }
    await writeReleaseModule(null);
    return;
  }
  await writeReleaseModule(rawReleaseSha);
}

const entryUrl = process.argv[1]
  ? pathToFileURL(process.argv[1]).href
  : "";
if (entryUrl === import.meta.url) {
  main().catch((error) => {
    process.stderr.write(`${error instanceof Error ? error.message : String(error)}\n`);
    process.exitCode = 1;
  });
}
